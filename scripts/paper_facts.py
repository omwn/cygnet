#!/usr/bin/env python3
"""Derive the figures the Cygnet paper cites, and write them as LaTeX macros.

Typing build figures into the paper by hand means every rebuild is followed by
a hunt through the text for the numbers that changed, and some are always
missed.  This recomputes them from a finished build and writes one macro per
figure, so the paper says \\fact{relations.reversed} and a rebuild updates it.

Sources (all produced by build.sh):
    web/cygnet.db                    the merged database
    bin/cygnets_presynth/            Step 2 conversion logs and manifest.txt
    bin/relation_conflicts.json      relations dropped while merging (Step 6)
    bin/raw_wns/                     the multilingual releases' language lexicons
    wordnets.toml                    where each wordnet was downloaded from

Integers get thousands separators in the .tex (1,747).  A key the paper uses
but the file lacks prints a bold ?? and a LaTeX warning, rather than failing
quietly.

Usage:
    uv run python scripts/paper_facts.py     # reports/facts.json, reports/facts.tex
    uv run python scripts/paper_facts.py --baseline lrec2026.db   # also first.*
    uv run python scripts/paper_facts.py --tex ~/papers/GWC/2027/cygnet/facts.tex
"""

from __future__ import annotations

import argparse
import json
import re
import sqlite3
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent

# Lexicons that are not wordnets: the concept index and the implicit PWN.
NOT_WORDNETS = {"cili", "pwn"}
# Multilingual releases: each is one wordnet, however many lexicons it has.
MULTILINGUAL_PREFIXES = ("omw-kin", "omw-pronoun")
# Wordnets converted to WN-LMF for the paper: those released from
# omw-converters, plus KeNet, which was converted for its developers and is
# now distributed from their repository.
CONVERTER_URL = "github.com/igamasniak/omw-converters/"
CONVERTED_ELSEWHERE = ("kenet",)

TEX_HEADER = r"""% Generated by cygnet/scripts/paper_facts.py from a Cygnet build.
% Do not edit by hand: rebuild Cygnet and rerun the script.
% Use as \fact{cygnet.languages}.
\providecommand{\fact}[1]{%
  \ifcsname fact@#1\endcsname\csname fact@#1\endcsname
  \else\textbf{??}\PackageWarning{facts}{Undefined fact `#1'}\fi}
"""


def is_multilingual(code: str) -> bool:
    """True if a resource code belongs to one of the multilingual releases."""
    return code.startswith(MULTILINGUAL_PREFIXES)


def coverage_facts(con: sqlite3.Connection) -> dict:
    """Languages, wordnets and size of the merged database.

    Args:
        con: Connection to cygnet.db.

    Returns:
        Facts under 'cygnet': languages (excluding 'mul'), wordnets (each
        multilingual release counted once), tufs (TUFS vocabularies among the
        wordnets), lexicons (every resource but CILI and PWN), and table sizes.
    """
    codes = [c for (c,) in con.execute("SELECT code FROM resources")
             if c not in NOT_WORDNETS]
    single = [c for c in codes if not is_multilingual(c)]
    releases = {p for p in MULTILINGUAL_PREFIXES for c in codes if c.startswith(p)}
    languages = con.execute("""
        SELECT COUNT(DISTINCT l.code)
        FROM entries e JOIN languages l ON l.rowid = e.language_rowid
        WHERE l.code != 'mul'
    """).fetchone()[0]

    def count(table: str) -> int:
        return con.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]

    return {
        "languages": languages,
        "wordnets": len(single) + len(releases),
        "tufs": sum(c.startswith("tufs-") for c in single),
        "lexicons": len(codes),
        "synsets": count("synsets"),
        "senses": count("senses"),
        "entries": count("entries"),
        "definitions": count("definitions"),
        "examples": count("examples"),
    }


def converted_facts(toml_text: str) -> dict:
    """How many wordnets were converted to WN-LMF for the paper.

    Args:
        toml_text: Contents of wordnets.toml.

    Returns:
        {'wordnets': n}: one per omw-converters URL, plus CONVERTED_ELSEWHERE.
    """
    urls = re.findall(r'"(https?://[^"]+)"', toml_text)
    from_converters = sum(CONVERTER_URL in u for u in urls)
    return {"wordnets": from_converters + len(CONVERTED_ELSEWHERE)}


def example_facts(presynth: Path) -> dict:
    """Examples dropped in conversion, over the files the build used.

    Args:
        presynth: The bin/cygnets_presynth directory.

    Returns:
        {'excluded': n, 'wordnets': m}: skipped examples summed over the Step 2
        logs of files in manifest.txt, and how many files had any.
    """
    planned = (presynth / "manifest.txt").read_text(encoding="utf-8").split()
    excluded = wordnets = 0
    for name in planned:
        log = presynth / name.replace(".xml", "_log.json")
        if not log.exists():
            continue
        stats = json.loads(log.read_text(encoding="utf-8")).get("statistics", {})
        skipped = stats.get("examples", {}).get("skipped", 0)
        excluded += skipped
        wordnets += skipped > 0
    return {"excluded": excluded, "wordnets": wordnets}


def relation_facts(conflicts: dict) -> dict:
    """Relations dropped while merging.

    Args:
        conflicts: Contents of relation_conflicts.json.

    Returns:
        reversed / reversed-wordnets: relations skipped because an earlier
        resource has the reverse; loops / loop-wordnets: hypernym relations
        removed because they would close a loop.
    """
    reversed_ = conflicts.get("reversed_relations", [])
    cycles = conflicts.get("cycles", [])
    return {
        "reversed": len(reversed_),
        "reversed-wordnets": len({r["resource_id"] for r in reversed_}),
        "loops": len(cycles),
        "loop-wordnets": len({c["xml_stem"] for c in cycles}),
    }


def multilingual_facts(con: sqlite3.Connection, raw_wns: Path) -> dict:
    """Languages in each multilingual release, and how many the build kept.

    A language lexicon is kept only if its language already has another
    wordnet in the build (see plan_multilexicon in 2_batch_convert_lmfs.py).

    Args:
        con: Connection to cygnet.db.
        raw_wns: The bin/raw_wns directory the release was unpacked into.

    Returns:
        For each release in the build, {'languages': n, 'kept': m}: its
        language lexicons (files of the built version, apart from the
        concepts lexicon) and those that became Cygnet resources.
    """
    facts = {}
    for prefix in MULTILINGUAL_PREFIXES:
        row = con.execute("SELECT version FROM resources WHERE code = ?",
                          (prefix,)).fetchone()
        if row is None:
            continue
        version = row[0]
        members = list(raw_wns.glob(f"{prefix}-*-{version}.xml*"))
        kept = con.execute("SELECT COUNT(*) FROM resources WHERE code LIKE ?",
                           (f"{prefix}-%",)).fetchone()[0]
        facts[prefix] = {"languages": len(members), "kept": kept}
    return facts


def baseline_facts(db: Path) -> dict:
    """Coverage of an earlier release, measured as coverage_facts() measures this one.

    Args:
        db: cygnet.db of the earlier release.

    Returns:
        The same keys as coverage_facts().
    """
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    try:
        return coverage_facts(con)
    finally:
        con.close()


def build_facts(db: Path, presynth: Path, conflicts: Path, toml: Path,
                raw_wns: Path) -> dict:
    """Every figure the paper cites, as a nested dict.

    Args:
        db: cygnet.db.
        presynth: bin/cygnets_presynth.
        conflicts: bin/relation_conflicts.json.
        toml: wordnets.toml.
        raw_wns: bin/raw_wns.

    Returns:
        Facts keyed by topic.
    """
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    try:
        cygnet = coverage_facts(con)
        multilingual = multilingual_facts(con, raw_wns)
    finally:
        con.close()
    return {
        "cygnet": cygnet,
        "converted": converted_facts(toml.read_text(encoding="utf-8")),
        "examples": example_facts(presynth),
        "relations": relation_facts(json.loads(conflicts.read_text(encoding="utf-8"))),
        "multilingual": multilingual,
    }


def flatten(node: object, path: str = "") -> dict[str, int | float]:
    """Every numeric leaf of a facts tree, keyed by its dotted path."""
    if isinstance(node, dict):
        out: dict[str, int | float] = {}
        for key, value in node.items():
            out.update(flatten(value, f"{path}.{key}" if path else str(key)))
        return out
    if isinstance(node, (int, float)) and not isinstance(node, bool):
        return {path: node}
    return {}


def render_tex(facts: dict) -> str:
    """The text of facts.tex: one \\fact macro per numeric leaf.

    Args:
        facts: Nested facts, as from build_facts().

    Returns:
        LaTeX source defining \\fact and every value.
    """
    lines = [TEX_HEADER]
    for path, value in sorted(flatten(facts).items()):
        text = f"{value:,}" if isinstance(value, int) else f"{value}"
        lines.append(rf"\expandafter\def\csname fact@{path}\endcsname{{{text}}}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--db", type=Path, default=PROJECT_ROOT / "web" / "cygnet.db")
    parser.add_argument("--presynth", type=Path,
                        default=PROJECT_ROOT / "bin" / "cygnets_presynth")
    parser.add_argument("--conflicts", type=Path,
                        default=PROJECT_ROOT / "bin" / "relation_conflicts.json")
    parser.add_argument("--toml", type=Path, default=PROJECT_ROOT / "wordnets.toml")
    parser.add_argument("--raw", type=Path, default=PROJECT_ROOT / "bin" / "raw_wns")
    parser.add_argument("--baseline", type=Path,
                        help="cygnet.db of an earlier release, measured as first.*")
    reports = PROJECT_ROOT / "reports"
    parser.add_argument("--json", type=Path, default=reports / "facts.json")
    parser.add_argument("--tex", type=Path, default=reports / "facts.tex")
    args = parser.parse_args()

    facts = build_facts(args.db, args.presynth, args.conflicts, args.toml, args.raw)
    if args.baseline:
        facts["first"] = baseline_facts(args.baseline)
    for out in (args.json, args.tex):
        out.parent.mkdir(parents=True, exist_ok=True)
    args.json.write_text(json.dumps(facts, indent=2) + "\n", encoding="utf-8")
    args.tex.write_text(render_tex(facts), encoding="utf-8")
    print(f"wrote {args.json} and {args.tex}: {len(flatten(facts))} facts",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
